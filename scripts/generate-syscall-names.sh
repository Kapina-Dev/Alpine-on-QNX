#!/bin/sh
# Regenerate src/linux_syscall_names.h (ARM EABI syscall number -> name)
# from the Android NDK's UAPI header. Usage:
#   ANDROID_NDK_HOME=/path/to/android-ndk-r27c sh scripts/generate-syscall-names.sh
set -eu

script_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
project_dir=$(CDPATH= cd -- "$script_dir/.." && pwd)
ndk=${ANDROID_NDK_HOME:?set ANDROID_NDK_HOME to an Android NDK}
header="$ndk/toolchains/llvm/prebuilt/linux-x86_64/sysroot/usr/include/arm-linux-androideabi/asm/unistd-eabi.h"
release=$(sed -n 's/^Pkg.Revision *= *//p' "$ndk/source.properties" 2>/dev/null || true)
out="$project_dir/src/linux_syscall_names.h"

[ -f "$header" ] || { echo "missing $header" >&2; exit 1; }

{
    echo "/* Generated by scripts/generate-syscall-names.sh from the Android NDK"
    echo "   ${release:-unknown} header asm/unistd-eabi.h (ARM EABI). Do not edit. */"
    echo "#ifndef LINUXEMU_LINUX_SYSCALL_NAMES_H"
    echo "#define LINUXEMU_LINUX_SYSCALL_NAMES_H"
    echo ""
    echo "#include <stdint.h>"
    echo ""
    echo "static const struct {"
    echo "    uint32_t number;"
    echo "    const char *name;"
    echo "} linux_syscall_names[] = {"
    {
        sed -n 's/^#define __NR_\([a-z0-9_]*\) (__NR_SYSCALL_BASE + \([0-9]*\))$/\2 \1/p' \
            "$header"
        # ARM private syscalls (__ARM_NR_BASE = 0x0f0000).
        printf '%d ARM_breakpoint\n' 0xf0001
        printf '%d ARM_cacheflush\n' 0xf0002
        printf '%d ARM_usr26\n' 0xf0003
        printf '%d ARM_usr32\n' 0xf0004
        printf '%d ARM_set_tls\n' 0xf0005
        printf '%d ARM_get_tls\n' 0xf0006
    } | sort -n | awk '{ printf "    { %su, \"%s\" },\n", $1, $2 }'
    echo "};"
    echo ""
    echo "#endif"
} > "$out"
echo "wrote $out ($(grep -c '^    {' "$out") entries)"
